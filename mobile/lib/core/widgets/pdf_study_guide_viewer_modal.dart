  static String _escapeHtml(String raw) {
    return raw
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;");
  }

  static String _convertMarkdownToHtml(String pageText) {
    final sb = StringBuffer();
    final lines = pageText.split(RegExp(r"\r?\n"));
    bool inList = false;

    for (final rawLine in lines) {
      final line = rawLine.trim();
      if (line.isEmpty) {
        if (inList) {
          sb.writeln("</ul>");
          inList = false;
        }
        continue;
      }

      if (line.startsWith("### ")) {
        if (inList) {
          sb.writeln("</ul>");
          inList = false;
        }
        sb.writeln("<h3>${_formatInlineBold(_escapeHtml(line.substring(4)))}</h3>");
      } else if (line.startsWith("## ") || line.startsWith("# ")) {
        if (inList) {
          sb.writeln("</ul>");
          inList = false;
        }
        final clean = line.replaceFirst(RegExp(r"^#+\s*"), "");
        sb.writeln("<h2>${_formatInlineBold(_escapeHtml(clean))}</h2>");
      } else if (line.startsWith("- ") || line.startsWith("• ") || line.startsWith("* ")) {
        if (!inList) {
          sb.writeln("<ul>");
          inList = true;
        }
        sb.writeln("<li>${_formatInlineBold(_escapeHtml(line.substring(2)))}</li>");
      } else if (line.contains("  |  ")) {
        if (inList) {
          sb.writeln("</ul>");
          inList = false;
        }
        sb.writeln('<div class="table-row">${_formatInlineBold(_escapeHtml(line))}</div>');
      } else {
        if (inList) {
          sb.writeln("</ul>");
          inList = false;
        }
        sb.writeln("<p>${_formatInlineBold(_escapeHtml(line))}</p>");
      }
    }
    if (inList) sb.writeln("</ul>");
    return sb.toString();
  }

  static String _formatInlineBold(String escaped) {
    return escaped.replaceAllMapped(
      RegExp(r"\*\*(.+?)\*\*"),
      (m) => "<strong>${m.group(1)}</strong>",
    );
  }

