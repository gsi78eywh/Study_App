  Widget _buildFormattedPaperLine(String rawLine) {
    final line = rawLine.trim();
    if (line.isEmpty) {
      return const SizedBox(height: 8);
    }
    if (line == "---") {
      return const Divider(color: Color(0xFFCBD5E1), height: 18);
    }

    // Major Section Heading (## or 📌 / 🗣️ / 📋)
    if (line.startsWith("## ") ||
        line.startsWith("# ") ||
        line.startsWith("📌 MAIN CONTENT") ||
        line.startsWith("📝 FULL SCANNED")) {
      final clean = line.replaceFirst(RegExp(r"^#+\s*"), "");
      return Container(
        width: double.infinity,
        margin: const EdgeInsets.only(top: 12, bottom: 6),
        padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
        decoration: BoxDecoration(
          color: const Color(0xFFEEF2FF),
          border: const Border(
            left: BorderSide(color: Color(0xFF4F46E5), width: 3.5),
          ),
          borderRadius: BorderRadius.circular(4),
        ),
        child: Text(
          clean.replaceAll("**", ""),
          style: GoogleFonts.outfit(
            fontSize: 14.5,
            fontWeight: FontWeight.w700,
            color: const Color(0xFF1E1B4B),
          ),
        ),
      );
    }

    // Subheading (###)
    if (line.startsWith("### ")) {
      final clean = line.substring(4).replaceAll("**", "");
      return Padding(
        padding: const EdgeInsets.only(top: 10, bottom: 4),
        child: Text(
          clean,
          style: const TextStyle(
            fontSize: 13.5,
            fontWeight: FontWeight.w700,
            color: Color(0xFF1E293B),
          ),
        ),
      );
    }

    // Table / Multi-Column Row (`  |  `)
    if (line.contains("  |  ")) {
      final cells = line.split("  |  ").map((c) => c.trim()).toList();
      return Container(
        margin: const EdgeInsets.symmetric(vertical: 2),
        padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 6),
        decoration: BoxDecoration(
          color: const Color(0xFFF1F5F9),
          border: Border.all(color: const Color(0xFFCBD5E1)),
          borderRadius: BorderRadius.circular(4),
        ),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: cells
              .map(
                (cell) => Expanded(
                  child: Padding(
                    padding: const EdgeInsets.symmetric(horizontal: 4),
                    child: Text(
                      cell.replaceAll("**", ""),
                      style: const TextStyle(
                        fontSize: 12,
                        color: Color(0xFF0F172A),
                        fontWeight: FontWeight.w500,
                      ),
                    ),
                  ),
                ),
              )
              .toList(),
        ),
      );
    }

    // Bullet List Item
    if (line.startsWith("- ") || line.startsWith("• ") || line.startsWith("* ")) {
      final itemText = line.substring(2).replaceAll("**", "");
      return Padding(
        padding: const EdgeInsets.only(left: 8, top: 3, bottom: 3),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              "•  ",
              style: TextStyle(
                fontSize: 13.5,
                fontWeight: FontWeight.bold,
                color: Color(0xFF4F46E5),
              ),
            ),
            Expanded(
              child: Text(
                itemText,
                style: const TextStyle(
                  fontSize: 13,
                  height: 1.5,
                  color: Color(0xFF1E293B),
                ),
              ),
            ),
          ],
        ),
      );
    }

    // Standard Paragraph
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 2.5),
      child: Text(
        line.replaceAll("**", ""),
        style: const TextStyle(
          fontSize: 13,
          height: 1.55,
          color: Color(0xFF1E293B),
        ),
      ),
    );
  }
