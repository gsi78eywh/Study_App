  /// Splits raw or markdown text into realistic A4 PDF pages (`--- Page N ---` or ~1,600 chars per page).
  static List<String> paginateDocument(String rawText) {
    final trimmed = rawText.trim();
    if (trimmed.isEmpty) return ["(Empty Document)"];

    // Check if explicit PDF page markers exist (`--- Page N ---`)
    final pageMarkerRegex = RegExp(r"---\s*Page\s+\d+\s*---", caseSensitive: false);
    if (pageMarkerRegex.hasMatch(trimmed)) {
      final parts = trimmed
          .split(pageMarkerRegex)
          .map((p) => p.trim())
          .where((p) => p.isNotEmpty)
          .toList();
      if (parts.isNotEmpty) return parts;
    }

    // Otherwise split cleanly by paragraphs into ~1,600 character visual pages
    final paragraphs = trimmed.split(RegExp(r"\n\s*\n"));
    final pages = <String>[];
    final current = StringBuffer();

    for (final para in paragraphs) {
      if (current.length + para.length > 1650 && current.isNotEmpty) {
        pages.add(current.toString().trim());
        current.clear();
      }
      if (current.isNotEmpty) current.writeln("\n");
      current.write(para.trim());
    }
    if (current.isNotEmpty) {
      pages.add(current.toString().trim());
    }
    return pages.isEmpty ? [trimmed] : pages;
  }

  /// Builds a standalone printable A4 PDF-styled HTML Study Guide.
